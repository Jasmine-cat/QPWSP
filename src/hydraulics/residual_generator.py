def _cleanup_epanet_artifacts(file_prefix: str) -> None:
    """
    Remove temporary files generated by WNTR/EPANET for a given file prefix.
    """
    if not file_prefix:
        return
    for p in glob.glob(file_prefix + ".*"):
        try:
            if os.path.isfile(p):
                os.remove(p)
        except Exception:
            # Best-effort cleanup; never break main flow due to temp-file deletion.
            pass

def _run_pressure_array_with_retry(wn, junction_names, *, tag, max_retries=0,
                                   retry_sleep_sec=0.05, required_time_s=None):
    return run_pressure_array(wn, junction_names, tag=tag, max_retries=max_retries,
                              retry_sleep_sec=retry_sleep_sec,
                              required_time_s=required_time_s)


def _load_step1_graph_meta(node_features_dir: str, inp_name: str) -> dict:
    meta_path = os.path.join(node_features_dir, f"{inp_name}_graph_meta.json")
    if not os.path.exists(meta_path):
        return {}
    with open(meta_path, "r", encoding="utf-8") as f:
        return json.load(f)


def _apply_time_settings_from_meta(
    wn: wntr.network.WaterNetworkModel,
    graph_meta: dict,
) -> tuple[int | None, int, int]:
    report_step_s = int(graph_meta.get("report_step_s", 3600))
    hydraulic_step_s = int(graph_meta.get("hydraulic_step_s", report_step_s))
    duration_raw = graph_meta.get("duration_s", None)
    duration_s: int | None = None
    if duration_raw is not None:
        duration_s = int(duration_raw)
    else:
        t_steps = int(graph_meta.get("t_steps", 0) or 0)
        if t_steps > 1:
            duration_s = int((t_steps - 1) * report_step_s)

    wn.options.time.report_timestep = int(report_step_s)
    wn.options.time.hydraulic_timestep = int(hydraulic_step_s)
    if duration_s is not None and duration_s >= 0:
        wn.options.time.duration = int(duration_s)

    return duration_s, report_step_s, hydraulic_step_s


def _strict_find_time_index(
    times: np.ndarray,
    selected_ptime_s: int,
    inp_name: str,
) -> int:
    times_arr = np.asarray(times, dtype=float).reshape(-1)
    matched = np.where(np.isclose(times_arr, float(selected_ptime_s), rtol=0.0, atol=1e-9))[0]
    if matched.size > 0:
        return int(matched[0])

    if times_arr.size == 0:
        raise ValueError(
            f"[RS][{inp_name}] selected_ptime_s={selected_ptime_s} is invalid: baseline times axis is empty."
        )

    t_min = float(np.min(times_arr))
    t_max = float(np.max(times_arr))
    if times_arr.size >= 2:
        diffs = np.diff(times_arr)
        finite_diffs = diffs[np.isfinite(diffs)]
        if finite_diffs.size > 0:
            approx_step = float(np.median(finite_diffs))
            step_msg = f"{approx_step:g}"
        else:
            step_msg = "unknown"
    else:
        step_msg = "unknown"

    raise ValueError(
        f"[RS][{inp_name}] selected_ptime_s={selected_ptime_s} is not on current times axis "
        f"(range=[{t_min:g},{t_max:g}], n={times_arr.size}, approx_step={step_msg}). "
        f"Please align step1 selected time with current duration/report/hydraulic settings first."
    )


def generate_RS_from_inp(
    inp_path: str,
    out_npz: str,
    n_leak_levels: int = 8,
    q0_json_path: Optional[str] = None,
    node_features_dir: Optional[str] = None,
    factor_min: float = 0.25,
    factor_max: float = 2.0,
    rs_high_failure_retry_factor: float = 0.1,
    _rs_retry_depth: int = 0,
    overwrite: bool = False,
) -> Dict[str, Any]:
    """
    从 .inp 文件生成 R, S 矩阵（Python 版复刻 Matlab 逻辑）。

    Parameters
    ----------
    inp_path : str
        EPANET .inp 文件路径
    out_npz : str
        输出 npz 文件路径
    leak_factor : float
        兼容旧参数，当前不再用于生成泄露强度（保留仅避免调用方报错）。
    n_leak_levels : int
        泄露强度级数（用于生成以 chosen_beta 为中心的倍率序列）
    q0_json_path : str | None
        可选，显式指定 q0.json 路径；若不提供，则自动按 inp_name 在 node_features_dir 下寻找。
    node_features_dir : str | None
        q0.json 所在目录（默认: <repo>/data/features）
    factor_min/factor_max : float
        生成倍率区间 [factor_min, factor_max]，并按几何序列均匀采样 n_leak_levels 个因子。

    Returns
    -------
    info : dict
        一些关键信息（节点数、泄露强度、运行时间等）
    """
    if Path(out_npz).exists() and not overwrite:
        raise FileExistsError(f"Refusing to overwrite existing RS asset: {out_npz}")
    print(f"[RS] 读取网络: {inp_path}")
    wn = wntr.network.WaterNetworkModel(inp_path)

    # --- 1. 基本节点信息 ---
    all_junction_names = list(wn.junction_name_list)
    all_junction_nodes = [wn.get_node(name) for name in all_junction_names]
    all_base_demands = np.array(
        [jn.demand_timeseries_list[0].base_value for jn in all_junction_nodes],
        dtype=float,
    )
    keep_junction = np.isfinite(all_base_demands) & (all_base_demands >= 0.0)
    skipped_negative = [
        str(name) for name, keep in zip(all_junction_names, keep_junction) if not bool(keep)
    ]
    if skipped_negative:
        print(
            f"[RS] 从泄漏/传感器候选集合剔除 {len(skipped_negative)} 个负需求 junction: "
            f"{skipped_negative[:8]}"
            f"{'...' if len(skipped_negative) > 8 else ''}"
        )
    junction_names = [name for name, keep in zip(all_junction_names, keep_junction) if bool(keep)]
    if len(junction_names) == 0:
        raise ValueError(f"[RS][{Path(inp_path).stem}] 没有可用的非负需求 junction 候选节点。")
    reservoir_names = list(wn.reservoir_name_list)
    jun_num = len(junction_names)
    print(f"[RS] Junction 数量: {jun_num}, Reservoir 数量: {len(reservoir_names)}")

    # junction 节点对象和基准需求
    junction_nodes = [wn.get_node(name) for name in junction_names]
    base_demands = np.array(
        [jn.demand_timeseries_list[0].base_value for jn in junction_nodes],
        dtype=float,
    )
    inp_name = os.path.splitext(os.path.basename(inp_path))[0]
    if q0_json_path is None:
        if node_features_dir is None:
            repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
            node_features_dir = os.path.join(repo_root, "data", "features")
        q0_json_path = os.path.join(node_features_dir, f"{inp_name}q0.json")

    if not os.path.exists(q0_json_path):
        raise FileNotFoundError(
            f"q0 json not found for '{inp_name}': {q0_json_path}. "
            f"Please run inp_graph_parser first or pass q0_json_path explicitly."
        )
    if node_features_dir is None:
        node_features_dir = os.path.dirname(os.path.abspath(q0_json_path))

    with open(q0_json_path, "r", encoding="utf-8") as f:
        q0_info = json.load(f)
    if "chosen_beta" not in q0_info:
        raise KeyError(
            f"'chosen_beta' missing in q0 json: {q0_json_path}. "
            f"Current keys={list(q0_info.keys())}"
        )
    chosen_beta = float(q0_info["chosen_beta"])

    beta_status = str(q0_info.get("beta_select_status", "ok")).strip().lower()
    if beta_status.startswith("0fallback"): chosen_beta = float(1.0)

    graph_meta = _load_step1_graph_meta(node_features_dir, inp_name)
    duration_cfg_s, report_step_cfg_s, hyd_step_cfg_s = _apply_time_settings_from_meta(wn, graph_meta)

    selected_ptime_s_disk: int | None = None
    selected_ptime_source = "fallback_computed"
    selected_ptime_method = str(
        q0_info.get(
            "selected_ptime_method",
            graph_meta.get("selected_ptime_method", SELECTED_PTIME_METHOD),
        )
    )
    selected_ptime_window_steps = int(
        q0_info.get(
            "selected_ptime_window_steps",
            graph_meta.get("selected_ptime_window_steps", SELECTED_PTIME_WINDOW_STEPS),
        )
    )
    if "selected_ptime_s" in q0_info:
        selected_ptime_s_disk = int(q0_info["selected_ptime_s"])
        selected_ptime_source = "q0_json"
    elif "selected_ptime_s" in graph_meta:
        selected_ptime_s_disk = int(graph_meta["selected_ptime_s"])
        selected_ptime_source = "graph_meta"

    wn._experiment_evaluation_time_s = selected_ptime_s_disk

    # --- 2. 基准工况模拟（无泄漏） ---
    print("[RS] 运行基准工况（无泄漏）模拟 ...")
    print(
        "[RS] baseline time settings from step1 meta: "
        f"duration={duration_cfg_s}, report_step={report_step_cfg_s}, hyd_step={hyd_step_cfg_s}"
    )
    np_origin, times = _run_pressure_array_with_retry(
        wn,
        junction_names,
        tag="baseline",
        max_retries=0,
    )
    T = np_origin.shape[0]

    print(f"[RS] 基准模拟时间步数 T = {T}")
    print("[RS] np_origin 形状:", np_origin.shape)

    # --- 3. 计算“全网最低压时刻” min_ptime_idx ---
    # Matlab 中：
    #   对每个节点 i: 找到压强最小时刻 index(i)；
    #   min_ptime = mode(index)
    # 这里等价实现：
    # --- 4. 计算 LDD，并以 chosen_beta 为中间值构造 q_levels ---
    # Matlab 里： LDD = 平均 junction 基准需求
    if selected_ptime_s_disk is not None:
        selected_ptime_s = int(selected_ptime_s_disk)
        min_ptime_idx = _strict_find_time_index(times, selected_ptime_s, inp_name)
    else:
        base_pressure_df = pd.DataFrame(
            np_origin,
            index=pd.Index(times, name="time"),
            columns=junction_names,
        )
        selected_ptime_s = int(
            compute_selected_ptime(
                base_pressure_df,
                node_feats=None,
                window_steps=int(selected_ptime_window_steps),
                prefer_high_std=True,
                verbose=True,
                log_prefix="[min_ptime]",
            )
        )
        selected_ptime_source = "recomputed_fallback"
        min_ptime_idx = _strict_find_time_index(times, selected_ptime_s, inp_name)
    print(
        f"[RS] unified selected_ptime_s={selected_ptime_s} "
        f"(source={selected_ptime_source}, idx={min_ptime_idx})"
    )

    positive_demands = base_demands[np.isfinite(base_demands) & (base_demands > 0)]
    if positive_demands.size == 0:
        raise ValueError(
            f"[RS][{inp_name}] No positive junction base demand found; cannot define leak intensity LDD."
        )
    LDD = float(positive_demands.mean())
    LDD_lps = float(LDD * 1000.0)
    q0_from_current_lps = float(LDD_lps * chosen_beta)
    print(
        f"[RS] LDD (mean positive junction base_demand) = {LDD:.6g} m3/s "
        f"({LDD_lps:.6g} LPS), n_positive={positive_demands.size}/{base_demands.size}"
    )

    # Cross-check against step1 q0.json so RS generation cannot silently drift
    # from the beta/q0 decision made by inp_graph_parser.
    rel_tol_q0 = 1e-4
    ldd_json_lps = q0_info.get("LDD_lps", None)
    if ldd_json_lps is not None:
        ldd_json_lps = float(ldd_json_lps)
        rel = abs(LDD_lps - ldd_json_lps) / max(abs(ldd_json_lps), 1e-12)
        if rel > rel_tol_q0:
            print(
                f"[RS][WARN] LDD mismatch with q0.json: "
                f"current_positive_LDD={LDD_lps:.10g} LPS, "
                f"json_LDD={ldd_json_lps:.10g} LPS, rel_diff={rel:.3g}"
            )

    q0_json_lps = q0_info.get("q0_LPS", None)
    if q0_json_lps is not None:
        q0_json_lps = float(q0_json_lps)
        rel = abs(q0_from_current_lps - q0_json_lps) / max(abs(q0_json_lps), 1e-12)
        if rel > rel_tol_q0:
            print(
                f"[RS][WARN] q0 mismatch with q0.json: "
                f"current_LDD*chosen_beta={q0_from_current_lps:.10g} LPS, "
                f"json_q0={q0_json_lps:.10g} LPS, rel_diff={rel:.3g}, "
                f"beta_select_status={beta_status}"
            )

    if n_leak_levels <= 0:
        raise ValueError("n_leak_levels must be >= 1.")
    if factor_min <= 0 or factor_max <= 0:
        raise ValueError("factor_min/factor_max must be > 0.")
    if n_leak_levels == 1:
        factors = np.array([1.0], dtype=float)
    else:
        factors = np.geomspace(float(factor_min), float(factor_max), int(n_leak_levels))

    beta_levels = chosen_beta * factors
    q_levels = (LDD * beta_levels).astype(float)
    if not np.all(np.isfinite(q_levels)) or np.any(q_levels <= 0):
        raise ValueError(
            f"[RS][{inp_name}] Invalid q_levels generated: {q_levels}. "
            "Leak intensities must be finite and positive."
        )

    print(f"[RS] chosen_beta (from q0) = {chosen_beta:.6g}  (q0_json={q0_json_path})")
    print("[RS] leak factors =", factors)
    print("[RS] beta_levels =", beta_levels)
    print("[RS] 泄露强度级数 q_levels =", q_levels)
    if int(_rs_retry_depth) > 0:
        print(
            f"[RS] 当前为强度降级重试结果：retry_depth={int(_rs_retry_depth)}, "
            f"retry_factor={float(rs_high_failure_retry_factor):.6g}"
        )

    # --- 5. 枚举泄露强度对 (q1, q2)，生成 R, S ---
    # Matlab: pair = length(qrand)*(length(qrand)-1)/2
    pairs: list[Tuple[int, int]] = []
    L = len(q_levels)
    for i in range(L):
        for j in range(i + 1, L):
            pairs.append((i, j))
    K_pairs = len(pairs)
    print(f"[RS] 泄露强度组合个数 K_pairs = {K_pairs} (与 Matlab pair 一致)")

    # Each level/node is simulated once. Failure is missing data, never zero signal.
    responses = np.full((L, jun_num, jun_num), np.nan)
    valid_levels = np.zeros((L, jun_num), dtype=bool)
    failed_details = []
    t0 = time.time()
    wn._experiment_evaluation_time_s = selected_ptime_s
    for level, flow in enumerate(q_levels):
        for leak_index, node_name in enumerate(junction_names):
            try:
                with constant_leak(wn, node_name, float(flow)):
                    pressure, leak_times = _run_pressure_array_with_retry(
                        wn, junction_names, tag=f"{inp_name}_q{level}_node{node_name}",
                        max_retries=0,
                    )
                ti = _strict_find_time_index(leak_times, selected_ptime_s, inp_name)
                residual = np_origin[min_ptime_idx] - pressure[ti]
                if not np.isfinite(residual).all():
                    raise ValueError("Non-finite pressure residual.")
                responses[level, :, leak_index] = residual
                valid_levels[level, leak_index] = True
            except Exception as error:
                failed_details.append({"level": level, "node": node_name,
                                       "error": repr(error)})
    R_list = [responses[i].copy() for i, j in pairs]
    S_list = [responses[j] / float(q_levels[j]) for i, j in pairs]
    valid_scenarios = np.asarray([valid_levels[i] & valid_levels[j] for i, j in pairs])
    pair_indices_kept = list(range(len(pairs)))
    if np.any((~valid_scenarios).mean(axis=1) > 0.30) and int(_rs_retry_depth) < 1:
        factor = float(rs_high_failure_retry_factor)
        if not 0 < factor < 1:
            raise ValueError("RS fallback factor must be between zero and one.")
        print(f"[RS] More than 30% failed: retry all levels once at {factor:g}x flow.")
        return generate_RS_from_inp(
            inp_path, out_npz, n_leak_levels=n_leak_levels,
            q0_json_path=q0_json_path, node_features_dir=node_features_dir,
            factor_min=float(factor_min)*factor, factor_max=float(factor_max)*factor,
            rs_high_failure_retry_factor=factor, _rs_retry_depth=1, overwrite=overwrite,
        )
    if not valid_scenarios.any():
        raise RuntimeError("No valid residual/dictionary simulation scenarios.")
    if np.any((~valid_scenarios).mean(axis=1) > 0.30):
        raise RuntimeError("RS failure ratio exceeds 30% after group flow recovery.")
    failed_col_fill_value = float("nan")

    elapsed = time.time() - t0
    print(f"\n[RS] 所有组合模拟完毕，总耗时 {elapsed:.2f} 秒")
    if failed_details:
        print(
            f"[RS][WARN] 节点级仿真失败总数={len(failed_details)} "
            f"(marked invalid, excluded by the common scenario mask)"
        )

    # --- 6. 组装为 3D 数组并存盘 ---
    if len(S_list) == 0 or len(R_list) == 0:
        raise RuntimeError(
            "No successful leakage pairs were generated; abort writing RS npz."
        )

    S_arr = np.stack(S_list, axis=0)  # (K_pairs, N_j, N_j)
    R_arr = np.stack(R_list, axis=0)  # (K_pairs, N_j, N_j)

    out_dir = os.path.dirname(out_npz)
    if out_dir and (not os.path.exists(out_dir)):
        os.makedirs(out_dir, exist_ok=True)

    tmp_npz = out_npz + ".tmp.npz"
    if os.path.exists(tmp_npz):
        os.remove(tmp_npz)
    try:
        np.savez_compressed(
            tmp_npz,
            R=R_arr,
            valid_scenarios=valid_scenarios,
            leak_node_names=np.array(junction_names),
            leak_model=np.array("constant_additional_demand"),
            node_level_failures=np.array([json.dumps(x) for x in failed_details]),
            S=S_arr,
            q_levels=q_levels,
            junction_names=np.array(junction_names),
            reservoir_names=np.array(reservoir_names),
            base_demands=base_demands,
            excluded_negative_demand_junctions=np.array(skipped_negative, dtype=str),
            times=times,
            min_ptime_idx=np.array(min_ptime_idx, dtype=int),
            selected_ptime_s=np.array(int(selected_ptime_s), dtype=int),
            selected_ptime_source=np.array(str(selected_ptime_source)),
            selected_ptime_method=np.array(str(selected_ptime_method)),
            selected_ptime_window_steps=np.array(int(selected_ptime_window_steps), dtype=int),
            duration_cfg_s=np.array(-1 if duration_cfg_s is None else int(duration_cfg_s), dtype=int),
            report_step_cfg_s=np.array(int(report_step_cfg_s), dtype=int),
            hyd_step_cfg_s=np.array(int(hyd_step_cfg_s), dtype=int),
            pairs_attempted=np.array(K_pairs, dtype=int),
            pairs_kept=np.array(len(pair_indices_kept), dtype=int),
            pairs_skipped=np.array(K_pairs - len(pair_indices_kept), dtype=int),
            pair_indices_kept=np.array(pair_indices_kept, dtype=int),
            chosen_beta=np.array(chosen_beta, dtype=float),
            beta_levels=np.array(beta_levels, dtype=float),
            leak_factors=np.array(factors, dtype=float),
            factor_min=np.array(float(factor_min), dtype=float),
            factor_max=np.array(float(factor_max), dtype=float),
            rs_high_failure_retry_factor=np.array(float(rs_high_failure_retry_factor), dtype=float),
            rs_retry_depth=np.array(int(_rs_retry_depth), dtype=int),
            q0_json_path=np.array(str(q0_json_path)),
        )
        os.replace(tmp_npz, out_npz)
    except Exception:
        if os.path.exists(tmp_npz):
            os.remove(tmp_npz)
        raise
    print(f"[RS] 已保存到: {out_npz}")

    info: Dict[str, Any] = {
        "inp_path": inp_path,
        "out_npz": out_npz,
        "jun_num": jun_num,
        "n_pairs": len(pair_indices_kept),
        "n_pairs_attempted": K_pairs,
        "n_pairs_kept": len(pair_indices_kept),
        "n_pairs_skipped": K_pairs - len(pair_indices_kept),
        # 兼容旧字段名：现在存放节点级失败详情。
        "skipped_details": failed_details,
        "n_node_level_failures": len(failed_details),
        "failed_fill_value": float(failed_col_fill_value),
        "q0_json_path": q0_json_path,
        "chosen_beta": float(chosen_beta),
        "leak_factors": factors.tolist(),
        "factor_min": float(factor_min),
        "factor_max": float(factor_max),
        "rs_high_failure_retry_factor": float(rs_high_failure_retry_factor),
        "rs_retry_depth": int(_rs_retry_depth),
        "beta_levels": beta_levels.tolist(),
        "leak_levels": q_levels,
        "selected_ptime_s": int(selected_ptime_s),
        "selected_ptime_source": str(selected_ptime_source),
        "selected_ptime_method": str(selected_ptime_method),
        "selected_ptime_window_steps": int(selected_ptime_window_steps),
        "duration_cfg_s": (None if duration_cfg_s is None else int(duration_cfg_s)),
        "report_step_cfg_s": int(report_step_cfg_s),
        "hyd_step_cfg_s": int(hyd_step_cfg_s),
        "min_ptime_idx": int(min_ptime_idx),
        "elapsed_sec": elapsed,
    }
    return info
